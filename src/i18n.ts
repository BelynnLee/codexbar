const dictionaries: Record<Locale, Record<TranslationKey, string>> = { en, "zh-Hans": zhHans };

let current: Locale = "en";

export function resolveLocale(preference: LocalePreference, systemLocale: string): Locale {
  if (preference === "en") return "en";
  if (preference === "zh-hans") return "zh-Hans";
  return systemLocale.toLowerCase().startsWith("zh") ? "zh-Hans" : "en";
}

export function setLocale(locale: Locale): void {
  current = locale;
}

export function activeLocale(): Locale {
  return current;
}

export function t(key: TranslationKey, vars?: Record<string, string | number>): string {
  let text: string = dictionaries[current][key] ?? en[key];
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.split(`{${name}}`).join(String(value));
    }
  }
  return text;
}
